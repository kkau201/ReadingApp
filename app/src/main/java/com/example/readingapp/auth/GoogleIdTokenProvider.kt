package com.example.readingapp.auth

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.example.readingapp.R
import com.example.readingapp.common.ActivityProvider
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import dagger.hilt.android.qualifiers.ApplicationContext
import javax.inject.Inject

/** Gets a Google ID token for the user, showing the Google account picker if needed. */
interface GoogleIdTokenProvider {
    /**
     * @throws NoActivityException if there is no Activity to show the account picker in.
     * @throws androidx.credentials.exceptions.GetCredentialCancellationException if the user
     *   dismissed the picker (Play services also reports some config errors this way).
     * @throws androidx.credentials.exceptions.GetCredentialException for other picker failures.
     */
    suspend fun requestIdToken(): String
}

class NoActivityException : IllegalStateException("No current Activity to show the account picker")

class CredentialManagerGoogleIdTokenProvider @Inject constructor(
    @ApplicationContext private val context: Context,
    private val activityProvider: ActivityProvider
) : GoogleIdTokenProvider {

    override suspend fun requestIdToken(): String {
        // Generated by the google-services plugin from the web OAuth client in google-services.json.
        val webClientId = context.getString(R.string.default_web_client_id)
        // Credential Manager needs an Activity context to show its bottom sheet.
        val activity = activityProvider.currentActivity() ?: throw NoActivityException()

        val request = GetCredentialRequest.Builder()
            .addCredentialOption(GetSignInWithGoogleOption.Builder(webClientId).build())
            .build()
        val credential = CredentialManager.create(context)
            .getCredential(activity, request)
            .credential

        if (credential !is CustomCredential ||
            credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
        ) {
            throw IllegalStateException("Unexpected credential type: ${credential.type}")
        }
        return GoogleIdTokenCredential.createFrom(credential.data).idToken
    }
}
